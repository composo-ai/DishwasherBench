/**
 * The wash record: one versioned JSON document per real wash (docs/design/scope.md,
 * "Calibration is a first-class feature"; the written specification is
 * docs/calibration/wash-record.md, which this file implements field for field).
 *
 * A record says what was washed and how (machine with measured values, programme with the
 * measured course of the run, consumables and water, every item with its pose and soils) and
 * what was seen afterwards or during the run (observations, each with how it was obtained and
 * its uncertainty). A record may also be a published result (`kind: 'literature'`), a record
 * generated by the simulator (`synthetic`) or a wash that has not been run yet (`planned`: a
 * load with an observation plan, for experiment ranking).
 *
 * Units and names follow the wire convention of docs/design/platform.md section 2:
 * millimetres, degrees, grams, quaternions as (w, x, y, z), with the unit in every field name
 * that is not SI (`position_mm`, `amount_g`, `t_s`, `temperature_c`).
 *
 * `validateWashRecord` checks a parsed JSON document and returns either the record or every
 * problem found, each with the path of the field and a sentence for a person. It checks the
 * structure and what can be checked without building a scene: that the machine, programme,
 * item types, regions, soils, methods and observation targets exist.
 */

