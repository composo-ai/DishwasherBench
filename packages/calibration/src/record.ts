/** Thrown by {@link parseWashRecord} for a document that is not a valid wash record. */
export class WashRecordError extends Error {
  override readonly name = 'WashRecordError';
  readonly issues: readonly RecordIssue[];
  constructor(issues: readonly RecordIssue[]) {
    super(
      `invalid wash record:\n  ${issues.map((i) => (i.path === '' ? i.message : `${i.path}: ${i.message}`)).join('\n  ')}`,
    );
    this.issues = issues;
  }
}

type Json = Record<string, unknown>;

function isObject(value: unknown): value is Json {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function isFiniteNumber(value: unknown): value is number {
  return typeof value === 'number' && Number.isFinite(value);
}

function isNumberList(value: unknown, length: number): boolean {
  return Array.isArray(value) && value.length === length && value.every(isFiniteNumber);
}

/** The shape of a custom item, SI. Throws a RangeError when the definition cannot be expanded. */
export function customShapeOf(custom: CustomShape): Shape {
  if ('tile' in custom) {
    const t = custom.tile;
    return expandGeometryMm({
      class: 'slab',
      material: t.material,
      lengthMm: t.length_mm,
      widthMm: t.width_mm,
      thicknessMm: t.thickness_mm,
      edgeRadiusMm: t.edge_radius_mm ?? t.thickness_mm / 4,
    });
  }
  return expandGeometryMm(custom.geometry);
}

/** The id of the soil at `index` of an item's soils. */
export function soilIdOf(soil: RecordSoil, index: number): string {
  return soil.id ?? `soil_${index + 1}`;
}

/** The id of an observation: its own, or `<item>.<kind>[.<target>][@t]`. */
export function observationIdOf(observation: RecordObservation): string {
  if (observation.id !== undefined) return observation.id;
  const target =
    observation.target?.soil !== undefined
      ? `.${observation.target.soil}`
      : observation.target?.region !== undefined
        ? `.${observation.target.region}`
        : '';
  const at = observation.at_s === undefined ? '' : `@${observation.at_s}`;
  return `${observation.item}.${observation.kind}${target}${at}`;
}

/** The region ids of an item of a record: those of its custom shape, or of its catalogue type. */
export function recordItemRegionIds(item: RecordItem): string[] {
  const shape = item.custom !== undefined ? customShapeOf(item.custom) : undefined;
  const regions =
    shape !== undefined
      ? shape.regions.map((r) => r.id)
      : hasItemType(item.type)
        ? instantiate(item.type).shape.regions.map((r) => r.id)
        : [];
  return [...new Set(regions)];
}

