/** What part of an item an observation is about. */
export interface ObservationTarget {
  /** A region of the item; or */
  readonly region?: string;
  /** one soil of the item, by its id (the patch it was applied to). */
  readonly soil?: string;
}

/** One observation of one item. */
export interface RecordObservation {
  /** Id unique in the record; default `<item>.<kind>[.<target>][@t]`. */
  readonly id?: string;
  readonly item: string;
  /** The part of the item observed; default the whole item. */
  readonly target?: ObservationTarget;
  /**
   * When it was taken: absent for the end of the programme, or seconds from its start for an
   * observation taken by opening the door during the run.
   */
  readonly at_s?: number;
  readonly kind: ObservationKind;
  /**
   * The observed value: `score` the IEC cleaning score 0 to 5; `area_fraction` the share of
   * the soiled area still soiled, 0 to 1; `visible_area` the visibly soiled area, mm2 (for a
   * residue far below one per cent of the soiled area, where a fraction says nothing);
   * `residual_mass` dry soil left, milligrams;
   * `mass_fraction` dry soil left as a share of the dry soil applied; `specks` a count;
   * `clean` true or false; `retained_water` millilitres standing in the item. Absent in a
   * planned record.
   */
  readonly value?: number | boolean;
  /**
   * Standard uncertainty in the unit of the value; default that of the method. For
   * `visible_area` the uncertainty is a factor, not a difference: `sd` is the standard
   * uncertainty of ln(area + floor), the floor being the registered `obs.areaFloorMm2`.
   */
  readonly sd?: number;
  /**
   * `visible_area` only: the range the area is taken to lie in, mm2 (`[lower, upper]`, the
   * value between them). Read as the central 90 % of the reading's error in ln(area + floor);
   * it gives the uncertainty of an observation that states no `sd` ({@link observationSd}).
   */
  readonly range?: readonly [number, number];
  /**
   * False for an observation that is recorded, predicted and reported but does not enter the
   * likelihood of a fit: a second reading of a residue another observation already counts
   * (the owner's verdict beside the area read off his photograph). Default true.
   */
  readonly fitted?: boolean;
  /** How it was obtained, a key of the record's methods. */
  readonly method: string;
  readonly notes?: string;
  /** File names of photographs. */
  readonly photos?: readonly string[];
}

/**
 * One observation of a group of items at the end of the programme: the mean of their IEC
 * cleaning scores, as a published test result gives it (a class mean of a round robin, the
 * mean over a load). `weight` lets a group be weighted to a composition other than that of
 * the record's load (the item types of a standard load of which the record holds only some).
 */
export interface RecordGroupObservation {
  /** Id unique among the group observations of the record. */
  readonly id: string;
  readonly kind: 'mean_score';
  /** The items the mean is taken over, each with its weight (default 1). */
  readonly items: readonly { readonly item: string; readonly weight?: number }[];
  /** The observed mean score, 0 to 5. Absent in a planned record. */
  readonly value?: number;
  /** Standard uncertainty of the mean, score points. */
  readonly sd: number;
  /** How it was obtained, a key of the record's methods. */
  readonly method: string;
  readonly notes?: string;
}

/** A door opening during the run. */
export interface RecordInterruption {
  readonly t_s: number;
  /** How long the door was open, seconds. */
  readonly open_s?: number;
  readonly notes?: string;
}

/**
 * One way the inputs of a wash may have been, for a record whose inputs were not measured (an
 * amount that was not weighed, a layer spread by hand). The simulation is replayed once per
 * scenario and the likelihood of the observations of an item is the weighted mean of its
 * likelihoods over the scenarios: the unknown inputs are integrated out, not fitted and not
 * taken as fact.
 */
export interface RecordScenario {
  /** Weight of the scenario, above 0; the weights are normalised. Default 1. */
  readonly weight?: number;
  /** Seed of the soil layout in this scenario; default the record's `level_seed`. */
  readonly level_seed?: number;
  /** Factor on the amount of every soil of an item, by item id; an item not named has 1. */
  readonly amount_factors?: Readonly<Record<string, number>>;
  /** Parameter overrides of this scenario on top of the record's own, by key (not of the water). */
  readonly params?: Readonly<Record<string, number | readonly number[] | string>>;
  readonly notes?: string;
}

/** How the record is to be simulated. */
export interface RecordSim {
  readonly tier?: 'official' | 'fast';
  /** Seeds of the soil layout and of the exposure sampling. */
  readonly level_seed?: number;
  readonly sim_seed?: number;
  /** Parameter overrides that belong to this wash (a detergent's composition, ...), by key. */
  readonly params?: Readonly<Record<string, number | readonly number[] | string>>;
  /**
   * The input scenarios of a wash whose inputs were not measured ({@link RecordScenario}).
   * The first is the nominal one: the record as written is reported at it. Absent or empty:
   * the record as written is the only scenario.
   */
  readonly scenarios?: readonly RecordScenario[];
}

