/**
 * Checks a parsed JSON document against the wash record format. Returns the record (the same
 * object, typed) or every problem found.
 */
export function validateWashRecord(json: unknown): Result<WashRecord, readonly RecordIssue[]> {
  const issues: RecordIssue[] = [];
  const bad = (path: string, message: string): void => {
    issues.push({ path, message });
  };
  if (!isObject(json)) return err([{ path: '', message: 'a wash record is a JSON object' }]);
  if (json['format'] !== WASH_RECORD_FORMAT) {
    bad('format', `must be "${WASH_RECORD_FORMAT}"`);
  }
  if (json['version'] !== WASH_RECORD_VERSION) {
    bad(
      'version',
      `unsupported version ${JSON.stringify(json['version'])}; this code reads version ${WASH_RECORD_VERSION}`,
    );
  }
  if (issues.length > 0) return err(issues);

  if (typeof json['id'] !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9_.-]{0,95}$/.test(json['id'])) {
    bad('id', 'must be a short identifier of letters, digits, ".", "_" and "-"');
  }
  const kind = json['kind'];
  if (typeof kind !== 'string' || !(WASH_RECORD_KINDS as readonly string[]).includes(kind)) {
    bad('kind', `must be one of ${WASH_RECORD_KINDS.join(', ')}`);
  }

  // ---- provenance
  const methods = new Set<string>();
  const methodSd = new Map<string, number>();
  const provenance = json['provenance'];
  if (!isObject(provenance)) {
    bad('provenance', 'is missing: a record says when, by whom and how its numbers were obtained');
  } else {
    if (provenance['date'] !== undefined) {
      if (
        typeof provenance['date'] !== 'string' ||
        !/^\d{4}-\d{2}-\d{2}([T ].*)?$/.test(provenance['date'])
      ) {
        bad('provenance.date', 'must be an ISO 8601 date such as 2026-10-18');
      }
    } else if (kind === 'measured') {
      bad('provenance.date', 'is missing: a measured record states the date of the wash');
    }
    if (kind === 'measured' && typeof provenance['by'] !== 'string') {
      bad('provenance.by', 'is missing: a measured record states who ran the wash');
    }
    if (
      kind === 'literature' &&
      (typeof provenance['source'] !== 'string' || provenance['source'] === '')
    ) {
      bad('provenance.source', 'is missing: a literature record cites its source');
    }
    const m = provenance['methods'];
    if (!isObject(m)) {
      bad('provenance.methods', 'is missing: list how the numbers were obtained, by a short key');
    } else {
      for (const [key, method] of Object.entries(m)) {
        const path = `provenance.methods.${key}`;
        if (!isObject(method) || typeof method['description'] !== 'string') {
          bad(path, 'needs a description of the instrument and procedure');
          continue;
        }
        methods.add(key);
        if (method['sd'] !== undefined) {
          if (!isFiniteNumber(method['sd']) || !(method['sd'] > 0)) {
            bad(`${path}.sd`, 'must be a positive number');
          } else methodSd.set(key, method['sd']);
        }
      }
    }
  }
  const checkMethod = (path: string, value: unknown, required: boolean): void => {
    if (value === undefined) {
      if (required)
        bad(path, 'is missing: say how the number was obtained (a key of provenance.methods)');
      return;
    }
    if (typeof value !== 'string' || !methods.has(value)) {
      bad(
        path,
        `"${String(value)}" is not a key of provenance.methods (${[...methods].join(', ') || 'none defined'})`,
      );
    }
  };

  // ---- machine
  const machineJson = json['machine'];
  let machine: ReturnType<typeof findMachine>;
  if (!isObject(machineJson) || typeof machineJson['id'] !== 'string') {
    bad('machine.id', 'is missing');
  } else {
    machine = findMachine(machineJson['id']);
    if (machine === undefined) bad('machine.id', `unknown machine "${machineJson['id']}"`);
    const heights = machineJson['basket_heights'];
    if (heights !== undefined) {
      if (!isObject(heights) || Object.values(heights).some((v) => typeof v !== 'string')) {
        bad('machine.basket_heights', 'must map basket ids to position ids');
      }
    }
    if (machineJson['config'] !== undefined && !isObject(machineJson['config'])) {
      bad('machine.config', 'must be a machine configuration object');
    }
    const measured = machineJson['measured'];
    if (measured !== undefined) {
      if (!Array.isArray(measured)) bad('machine.measured', 'must be a list');
      else {
        measured.forEach((entry: unknown, i) => {
          const path = `machine.measured[${i}]`;
          if (!isObject(entry)) {
            bad(path, 'must be an object');
            return;
          }
          checkMethod(`${path}.method`, entry['method'], true);
          switch (entry['quantity']) {
            case 'spec':
              if (typeof entry['path'] !== 'string' || entry['path'] === '') {
                bad(
                  `${path}.path`,
                  'is missing: the path of the field in the machine specification',
                );
              }
              if (!isFiniteNumber(entry['value'])) bad(`${path}.value`, 'must be a number (SI)');
              break;
            case 'nozzle_diameter':
              if (typeof entry['level'] !== 'string') bad(`${path}.level`, 'is missing');
              if (typeof entry['nozzle'] !== 'string') bad(`${path}.nozzle`, 'is missing');
              if (!isFiniteNumber(entry['value_mm']) || !(entry['value_mm'] > 0)) {
                bad(`${path}.value_mm`, 'must be a positive number of millimetres');
              }
              break;
            case 'arm_speed':
              if (typeof entry['level'] !== 'string') bad(`${path}.level`, 'is missing');
              if (typeof entry['position'] !== 'string') bad(`${path}.position`, 'is missing');
              if (!isFiniteNumber(entry['pump_rpm']) || !(entry['pump_rpm'] > 0)) {
                bad(`${path}.pump_rpm`, 'must be a positive pump speed, rev/min');
              }
              if (!isFiniteNumber(entry['value_rpm']) || !(entry['value_rpm'] > 0)) {
                bad(`${path}.value_rpm`, 'must be a positive rotation rate, rev/min');
              }
              break;
            default:
              bad(
                `${path}.quantity`,
                `unknown quantity ${JSON.stringify(entry['quantity'])} (spec, nozzle_diameter, arm_speed)`,
              );
          }
        });
      }
    }
  }

  // ---- programme
  const programmeJson = json['programme'];
  if (!isObject(programmeJson) || typeof programmeJson['id'] !== 'string') {
    bad('programme.id', 'is missing');
  } else {
    const programme =
      machine === undefined ? undefined : findProgramme(machine, programmeJson['id']);
    if (machine !== undefined && programme === undefined) {
      bad(
        'programme.id',
        `machine ${machine.id} has no programme "${programmeJson['id']}" (${machine.programmes.map((p) => p.id).join(', ')})`,
      );
    }
    const course = programmeJson['course'];
    if (course !== undefined) {
      if (!isObject(course)) bad('programme.course', 'must be an object');
      else {
        if (
          course['duration_s'] !== undefined &&
          (!isFiniteNumber(course['duration_s']) || !(course['duration_s'] > 0))
        ) {
          bad('programme.course.duration_s', 'must be a positive number of seconds');
        }
        for (const name of ['power_log', 'temperature_log'] as const) {
          const log = course[name];
          if (log === undefined) continue;
          const path = `programme.course.${name}`;
          if (!isObject(log)) {
            bad(path, 'must be an object with t_s and values');
            continue;
          }
          const t = log['t_s'];
          const v = log['values'];
          if (!Array.isArray(t) || !t.every(isFiniteNumber)) {
            bad(`${path}.t_s`, 'must be a list of times in seconds');
          } else if (t.some((x, i) => i > 0 && !(x > (t[i - 1] as number)))) {
            bad(`${path}.t_s`, 'must be strictly ascending');
          }
          if (!Array.isArray(v) || !v.every(isFiniteNumber)) {
            bad(`${path}.values`, 'must be a list of numbers');
          } else if (Array.isArray(t) && t.length !== v.length) {
            bad(`${path}.values`, `has ${v.length} readings for ${t.length} times`);
          }
          checkMethod(`${path}.method`, log['method'], true);
        }
        const events = course['events'];
        if (events !== undefined) {
          if (!Array.isArray(events)) bad('programme.course.events', 'must be a list');
          else {
            events.forEach((event: unknown, i) => {
              const path = `programme.course.events[${i}]`;
              if (!isObject(event)) {
                bad(path, 'must be an object');
                return;
              }
              if (typeof event['kind'] !== 'string' || !EVENT_KINDS.includes(event['kind'])) {
                bad(`${path}.kind`, `must be one of ${EVENT_KINDS.join(', ')}`);
              }
              if (!isFiniteNumber(event['t_s']) || event['t_s'] < 0) {
                bad(`${path}.t_s`, 'must be a time in seconds from the start of the programme');
              }
              if (
                event['volume_l'] !== undefined &&
                (!isFiniteNumber(event['volume_l']) || event['volume_l'] < 0)
              ) {
                bad(`${path}.volume_l`, 'must be a volume in litres');
              }
            });
          }
        }
        const steps = course['steps'];
        if (steps !== undefined) {
          if (!Array.isArray(steps)) bad('programme.course.steps', 'must be a list');
          else {
            steps.forEach((step: unknown, i) => {
              const path = `programme.course.steps[${i}]`;
              if (!isObject(step) || typeof step['step'] !== 'string') {
                bad(`${path}.step`, 'is missing: the id of a step of the programme');
                return;
              }
              if (programme !== undefined && !programme.steps.some((s) => s.id === step['step'])) {
                bad(
                  `${path}.step`,
                  `programme ${programme.id} has no step "${step['step']}" (${programme.steps.map((s) => s.id).join(', ')})`,
                );
              }
              for (const field of ['duration_s', 'target_c', 'mains_volume_l'] as const) {
                if (
                  step[field] !== undefined &&
                  (!isFiniteNumber(step[field]) || step[field] < 0)
                ) {
                  bad(`${path}.${field}`, 'must be a non-negative number');
                }
              }
            });
          }
        }
      }
    }
  }

  // ---- consumables
  const consumables = json['consumables'];
  if (consumables !== undefined) {
    if (!isObject(consumables)) bad('consumables', 'must be an object');
    else {
      const detergent = consumables['detergent'];
      if (detergent !== undefined) {
        if (!isObject(detergent)) bad('consumables.detergent', 'must be an object');
        else {
          if (typeof detergent['product'] !== 'string') {
            bad('consumables.detergent.product', 'is missing: the product name');
          }
          if (
            typeof detergent['form'] !== 'string' ||
            !DETERGENT_FORMS.includes(detergent['form'])
          ) {
            bad('consumables.detergent.form', `must be one of ${DETERGENT_FORMS.join(', ')}`);
          }
          if (!isFiniteNumber(detergent['dose_g']) || detergent['dose_g'] < 0) {
            bad('consumables.detergent.dose_g', 'must be a mass in grams');
          }
          checkMethod('consumables.detergent.method', detergent['method'], false);
        }
      }
      const rinseAid = consumables['rinse_aid'];
      if (rinseAid !== undefined) {
        if (!isObject(rinseAid)) bad('consumables.rinse_aid', 'must be an object');
        else if (
          rinseAid['dose_ml'] !== undefined &&
          (!isFiniteNumber(rinseAid['dose_ml']) || rinseAid['dose_ml'] < 0)
        ) {
          bad('consumables.rinse_aid.dose_ml', 'must be a volume in millilitres');
        }
      }
      const water = consumables['water'];
      if (water !== undefined) {
        if (!isObject(water)) bad('consumables.water', 'must be an object');
        else {
          for (const field of [
            'hardness_dh',
            'bicarbonate_mmol_l',
            'inlet_temperature_c',
            'ambient_temperature_c',
          ] as const) {
            if (water[field] !== undefined && (!isFiniteNumber(water[field]) || water[field] < 0)) {
              bad(`consumables.water.${field}`, 'must be a non-negative number');
            }
          }
          checkMethod('consumables.water.method', water['method'], false);
        }
      }
    }
  }

  // ---- load
  const itemSoils = new Map<string, Set<string>>();
  const itemRegions = new Map<string, Set<string>>();
  const load = json['load'];
  if (!isObject(load) || !Array.isArray(load['items'])) {
    bad('load.items', 'is missing: the list of items');
  } else {
    (load['items'] as unknown[]).forEach((item, i) => {
      const path = `load.items[${i}]`;
      if (!isObject(item)) {
        bad(path, 'must be an object');
        return;
      }
      const id = item['id'];
      if (typeof id !== 'string' || !isValidId(id)) {
        bad(`${path}.id`, 'must be a valid identifier (lower-case letters, digits and "_")');
        return;
      }
      if (itemSoils.has(id)) bad(`${path}.id`, `"${id}" is used twice`);
      const soilIds = new Set<string>();
      itemSoils.set(id, soilIds);
      let regions: string[] = [];
      if (item['custom'] !== undefined) {
        const custom = item['custom'];
        if (!isObject(custom) || (!isObject(custom['tile']) && !isObject(custom['geometry']))) {
          bad(`${path}.custom`, 'must hold a "tile" or a "geometry"');
        } else {
          if (typeof item['type'] === 'string' && hasItemType(item['type'])) {
            bad(
              `${path}.type`,
              `"${item['type']}" is a catalogue item type; give a custom item a label of its own`,
            );
          }
          try {
            regions = [...new Set(customShapeOf(custom as CustomShape).regions.map((r) => r.id))];
          } catch (error) {
            bad(
              `${path}.custom`,
              `cannot be built: ${error instanceof Error ? error.message : String(error)}`,
            );
          }
        }
        if (typeof item['type'] !== 'string' || item['type'] === '') {
          bad(`${path}.type`, 'is missing: a label for the custom item');
        }
      } else if (typeof item['type'] !== 'string' || !hasItemType(item['type'])) {
        bad(`${path}.type`, `unknown item type "${String(item['type'])}"`);
      } else {
        regions = [...new Set(instantiate(item['type']).shape.regions.map((r) => r.id))];
      }
      itemRegions.set(id, new Set(regions));
      if (!isNumberList(item['position_mm'], 3)) {
        bad(`${path}.position_mm`, 'must be three numbers (millimetres)');
      }
      const quat = item['quat_wxyz'];
      if (!isNumberList(quat, 4)) {
        bad(`${path}.quat_wxyz`, 'must be four numbers (w, x, y, z)');
      } else if (Math.hypot(...(quat as number[])) < 1e-9) {
        bad(`${path}.quat_wxyz`, 'is zero');
      }
      if (item['frame'] !== undefined && typeof item['frame'] !== 'string') {
        bad(`${path}.frame`, 'must be "tub" or a basket frame');
      }
      if (!Array.isArray(item['soils'])) {
        bad(`${path}.soils`, 'is missing: the list of soils (empty for a clean item)');
        return;
      }
      (item['soils'] as unknown[]).forEach((soil, k) => {
        const sp = `${path}.soils[${k}]`;
        if (!isObject(soil)) {
          bad(sp, 'must be an object');
          return;
        }
        const soilId = typeof soil['id'] === 'string' ? soil['id'] : `soil_${k + 1}`;
        if (soilIds.has(soilId)) bad(`${sp}.id`, `"${soilId}" is used twice on ${id}`);
        soilIds.add(soilId);
        const type = soil['type'];
        if (
          typeof type !== 'string' ||
          !(hasSoil(type) || (SOIL_MODEL_CLASSES as readonly string[]).includes(type))
        ) {
          bad(
            `${sp}.type`,
            `unknown soil "${String(type)}": give a catalogue soil id or one of ${SOIL_MODEL_CLASSES.join(', ')}`,
          );
        }
        if (!isFiniteNumber(soil['amount_g']) || !(soil['amount_g'] > 0)) {
          bad(`${sp}.amount_g`, 'must be a positive mass in grams (the amount applied, wet)');
        }
        if (
          soil['amount_sd_g'] !== undefined &&
          (!isFiniteNumber(soil['amount_sd_g']) || soil['amount_sd_g'] < 0)
        ) {
          bad(`${sp}.amount_sd_g`, 'must be a non-negative mass in grams');
        }
        checkMethod(`${sp}.amount_method`, soil['amount_method'], kind === 'measured');
        const where = soil['where'];
        if (!isObject(where)) {
          bad(`${sp}.where`, 'is missing: give "regions" or a "patch"');
        } else if (where['patch'] !== undefined) {
          const patch = where['patch'];
          const pp = `${sp}.where.patch`;
          if (!isObject(patch)) bad(pp, 'must be an object');
          else {
            if (typeof patch['region'] !== 'string' || !regions.includes(patch['region'])) {
              bad(
                `${pp}.region`,
                `item ${id} has no region "${String(patch['region'])}" (${regions.join(', ')})`,
              );
            }
            if (!isNumberList(patch['centre_mm'], 3)) {
              bad(`${pp}.centre_mm`, 'must be three numbers (millimetres, item frame)');
            }
            if (patch['shape'] === 'disc') {
              if (!isFiniteNumber(patch['diameter_mm']) || !(patch['diameter_mm'] > 0)) {
                bad(`${pp}.diameter_mm`, 'a disc needs a positive diameter in millimetres');
              }
            } else if (patch['shape'] === 'rect') {
              if (
                !isNumberList(patch['size_mm'], 2) ||
                (patch['size_mm'] as number[]).some((s) => !(s > 0))
              ) {
                bad(`${pp}.size_mm`, 'a rectangle needs two positive side lengths in millimetres');
              }
              if (patch['u_axis'] !== undefined && !isNumberList(patch['u_axis'], 3)) {
                bad(`${pp}.u_axis`, 'must be three numbers');
              }
            } else {
              bad(`${pp}.shape`, 'must be "disc" or "rect"');
            }
          }
        } else if (Array.isArray(where['regions']) && where['regions'].length > 0) {
          (where['regions'] as unknown[]).forEach((entry, r) => {
            const rp = `${sp}.where.regions[${r}]`;
            if (!isObject(entry) || typeof entry['region'] !== 'string') {
              bad(rp, 'must be { region, coverage }');
              return;
            }
            if (!regions.includes(entry['region'])) {
              bad(
                `${rp}.region`,
                `item ${id} has no region "${entry['region']}" (${regions.join(', ')})`,
              );
            }
            const coverage = entry['coverage'];
            if (!isFiniteNumber(coverage) || !(coverage > 0) || coverage > 1) {
              bad(`${rp}.coverage`, 'must be above 0 and at most 1');
            }
          });
        } else {
          bad(`${sp}.where`, 'must hold a non-empty "regions" list or a "patch"');
        }
        const drying = soil['drying'];
        if (!isObject(drying) || !isFiniteNumber(drying['time_h']) || drying['time_h'] < 0) {
          bad(`${sp}.drying.time_h`, 'is missing: hours from application to the start of the wash');
        }
        const heat = soil['heat'];
        if (
          !isObject(heat) ||
          typeof heat['history'] !== 'string' ||
          !HEAT_HISTORIES.includes(heat['history'])
        ) {
          bad(`${sp}.heat.history`, `must be one of ${HEAT_HISTORIES.join(', ')}`);
        } else {
          for (const field of ['temperature_c', 'time_min'] as const) {
            if (heat[field] !== undefined && (!isFiniteNumber(heat[field]) || !(heat[field] > 0))) {
              bad(`${sp}.heat.${field}`, 'must be a positive number');
            }
          }
          if (
            heat['history'] === 'none' &&
            (heat['temperature_c'] !== undefined || heat['time_min'] !== undefined)
          ) {
            bad(
              `${sp}.heat.history`,
              'is "none" but a temperature or time is given: name the category of the heating (warm, cooked, baked, burnt)',
            );
          }
        }
      });
    });
    const stalled = load['stalled_arms_deg'];
    if (stalled !== undefined) {
      if (!isObject(stalled) || Object.values(stalled).some((v) => !isFiniteNumber(v))) {
        bad('load.stalled_arms_deg', 'must map spray level ids to angles in degrees');
      }
    }
  }

  // ---- observations
  const observations = json['observations'];
  const seenObservation = new Set<string>();
  if (!Array.isArray(observations)) {
    bad('observations', 'is missing: the list of observations (empty if none were taken)');
  } else {
    (observations as unknown[]).forEach((observation, i) => {
      const path = `observations[${i}]`;
      if (!isObject(observation)) {
        bad(path, 'must be an object');
        return;
      }
      const item = observation['item'];
      if (typeof item !== 'string' || !itemSoils.has(item)) {
        bad(`${path}.item`, `"${String(item)}" is not an item of the load`);
        return;
      }
      const obsKind = observation['kind'];
      if (
        typeof obsKind !== 'string' ||
        !(OBSERVATION_KINDS as readonly string[]).includes(obsKind)
      ) {
        bad(`${path}.kind`, `must be one of ${OBSERVATION_KINDS.join(', ')}`);
        return;
      }
      const target = observation['target'];
      if (target !== undefined) {
        if (!isObject(target)) bad(`${path}.target`, 'must be { region } or { soil }');
        else {
          if (target['region'] !== undefined && target['soil'] !== undefined) {
            bad(`${path}.target`, 'names a region and a soil; give one of them');
          }
          if (
            target['region'] !== undefined &&
            !(itemRegions.get(item)?.has(String(target['region'])) ?? false)
          ) {
            bad(
              `${path}.target.region`,
              `item ${item} has no region "${String(target['region'])}"`,
            );
          }
          if (
            target['soil'] !== undefined &&
            !(itemSoils.get(item)?.has(String(target['soil'])) ?? false)
          ) {
            bad(
              `${path}.target.soil`,
              `item ${item} has no soil "${String(target['soil'])}" (${[...(itemSoils.get(item) ?? [])].join(', ')})`,
            );
          }
        }
      }
      const at = observation['at_s'];
      if (at !== undefined) {
        if (!isFiniteNumber(at) || at < 0) {
          bad(`${path}.at_s`, 'must be a time in seconds from the start of the programme');
        }
        if (obsKind === 'retained_water') {
          bad(`${path}.at_s`, 'retained water can only be observed at the end of the programme');
        }
      }
      const value = observation['value'];
      if (value === undefined) {
        if (kind !== 'planned') {
          bad(`${path}.value`, 'is missing (only a planned record may leave values out)');
        }
      } else {
        switch (obsKind) {
          case 'score':
            if (!isFiniteNumber(value) || value < 0 || value > 5 || !Number.isInteger(value)) {
              bad(`${path}.value`, 'an IEC cleaning score is a whole number from 0 to 5');
            }
            break;
          case 'area_fraction':
          case 'mass_fraction':
            if (
              !isFiniteNumber(value) ||
              value < (obsKind === 'area_fraction' ? 0 : -0.5) ||
              value > 1.5
            ) {
              bad(`${path}.value`, 'a fraction lies between 0 and 1');
            } else if (obsKind === 'area_fraction' && value > 1) {
              bad(`${path}.value`, 'a fraction lies between 0 and 1');
            }
            break;
          case 'visible_area':
            if (!isFiniteNumber(value) || value < 0) {
              bad(`${path}.value`, 'must be an area in square millimetres, 0 or more');
            }
            break;
          case 'residual_mass':
            if (!isFiniteNumber(value)) bad(`${path}.value`, 'must be a mass in milligrams');
            break;
          case 'specks':
            if (!isFiniteNumber(value) || value < 0 || !Number.isInteger(value)) {
              bad(`${path}.value`, 'a speck count is a whole number, 0 or more');
            }
            break;
          case 'clean':
            if (typeof value !== 'boolean') bad(`${path}.value`, 'must be true or false');
            break;
          case 'retained_water':
            if (!isFiniteNumber(value) || value < 0) {
              bad(`${path}.value`, 'must be a volume in millilitres');
            }
            break;
        }
      }
      checkMethod(`${path}.method`, observation['method'], true);
      const range = observation['range'];
      if (range !== undefined) {
        if (obsKind !== 'visible_area') {
          bad(`${path}.range`, 'only an observation of kind visible_area states a range');
        } else if (
          !isNumberList(range, 2) ||
          (range as number[])[0]! < 0 ||
          !((range as number[])[1]! > (range as number[])[0]!)
        ) {
          bad(`${path}.range`, 'must be [lower, upper] in square millimetres, 0 <= lower < upper');
        } else if (
          isFiniteNumber(value) &&
          (value < (range as number[])[0]! || value > (range as number[])[1]!)
        ) {
          bad(`${path}.range`, 'must hold the value');
        }
      }
      if (observation['fitted'] !== undefined && typeof observation['fitted'] !== 'boolean') {
        bad(`${path}.fitted`, 'must be true or false');
      }
      const sd = observation['sd'];
      if (sd !== undefined) {
        if (!isFiniteNumber(sd) || !(sd > 0)) bad(`${path}.sd`, 'must be a positive number');
      } else if (obsKind === 'visible_area' && range !== undefined) {
        // The range gives the uncertainty.
      } else if (obsKind !== 'clean' && obsKind !== 'specks' && obsKind !== 'score') {
        const method = observation['method'];
        if (kind === 'literature') {
          bad(
            `${path}.sd`,
            'is missing: every observation of a literature record states its own uncertainty',
          );
        } else if (typeof method === 'string' && methods.has(method) && !methodSd.has(method)) {
          bad(
            `${path}.sd`,
            `is missing and method "${method}" has no default sd: every observation needs an uncertainty`,
          );
        }
      }
      if (
        observation['photos'] !== undefined &&
        (!Array.isArray(observation['photos']) ||
          observation['photos'].some((p) => typeof p !== 'string'))
      ) {
        bad(`${path}.photos`, 'must be a list of file names');
      }
      const id = observationIdOf(observation as unknown as RecordObservation);
      if (seenObservation.has(id)) {
        bad(`${path}.id`, `two observations have the id "${id}"; give one of them an id`);
      }
      seenObservation.add(id);
    });
  }

  // ---- observations of groups of items
  const groups = json['group_observations'];
  if (groups !== undefined) {
    if (!Array.isArray(groups)) bad('group_observations', 'must be a list');
    else {
      const loadItems = isObject(json['load']) ? json['load']['items'] : undefined;
      const known = new Set<string>(
        Array.isArray(loadItems)
          ? (loadItems as unknown[]).flatMap((item) =>
              isObject(item) && typeof item['id'] === 'string' ? [item['id']] : [],
            )
          : [],
      );
      const seenGroup = new Set<string>();
      (groups as unknown[]).forEach((group, i) => {
        const path = `group_observations[${i}]`;
        if (!isObject(group)) {
          bad(path, 'must be an object');
          return;
        }
        const id = group['id'];
        if (typeof id !== 'string' || id === '') bad(`${path}.id`, 'is missing');
        else if (seenGroup.has(id)) bad(`${path}.id`, `two group observations have the id "${id}"`);
        else seenGroup.add(id);
        if (group['kind'] !== 'mean_score') {
          bad(`${path}.kind`, 'must be "mean_score": the mean IEC score of the items');
        }
        const members = group['items'];
        if (!Array.isArray(members) || members.length === 0) {
          bad(`${path}.items`, 'must list at least one item');
        } else {
          (members as unknown[]).forEach((member, k) => {
            if (!isObject(member) || typeof member['item'] !== 'string') {
              bad(`${path}.items[${k}].item`, 'is missing: the id of an item of the load');
              return;
            }
            if (!known.has(member['item'])) {
              bad(`${path}.items[${k}].item`, `"${member['item']}" is not an item of the load`);
            }
            const weight = member['weight'];
            if (weight !== undefined && (!isFiniteNumber(weight) || !(weight > 0))) {
              bad(`${path}.items[${k}].weight`, 'must be above 0');
            }
          });
        }
        const value = group['value'];
        if (value !== undefined && (!isFiniteNumber(value) || value < 0 || value > 5)) {
          bad(`${path}.value`, 'must be a mean IEC score, 0 to 5');
        }
        if (!isFiniteNumber(group['sd']) || !(group['sd'] > 0)) {
          bad(`${path}.sd`, 'is missing: the standard uncertainty of the mean, above 0');
        }
        if (typeof group['method'] !== 'string' || group['method'] === '') {
          bad(`${path}.method`, 'is missing: how the mean was obtained');
        }
      });
    }
  }

  // ---- the rest
  const interruptions = json['interruptions'];
  if (interruptions !== undefined) {
    if (!Array.isArray(interruptions)) bad('interruptions', 'must be a list');
    else {
      interruptions.forEach((entry: unknown, i) => {
        if (!isObject(entry) || !isFiniteNumber(entry['t_s']) || entry['t_s'] < 0) {
          bad(`interruptions[${i}].t_s`, 'must be a time in seconds');
        }
      });
    }
  }
  const weight = json['weight'];
  if (weight !== undefined && (!isFiniteNumber(weight) || !(weight > 0) || weight > 1)) {
    bad('weight', 'must be above 0 and at most 1');
  }
  const sim = json['sim'];
  if (sim !== undefined) {
    if (!isObject(sim)) bad('sim', 'must be an object');
    else {
      if (sim['tier'] !== undefined && sim['tier'] !== 'official' && sim['tier'] !== 'fast') {
        bad('sim.tier', 'must be "official" or "fast"');
      }
      for (const field of ['level_seed', 'sim_seed'] as const) {
        const seed = sim[field];
        if (
          seed !== undefined &&
          (!isFiniteNumber(seed) || !Number.isInteger(seed) || seed < 0 || seed > 0xffffffff)
        ) {
          bad(`sim.${field}`, 'must be a whole number from 0 to 4294967295');
        }
      }
      if (sim['params'] !== undefined && !isObject(sim['params'])) {
        bad('sim.params', 'must map parameter keys to values');
      }
      const scenarios = sim['scenarios'];
      if (scenarios !== undefined) {
        if (!Array.isArray(scenarios)) bad('sim.scenarios', 'must be a list');
        else {
          (scenarios as unknown[]).forEach((scenario, i) => {
            const path = `sim.scenarios[${i}]`;
            if (!isObject(scenario)) {
              bad(path, 'must be an object');
              return;
            }
            const w = scenario['weight'];
            if (w !== undefined && (!isFiniteNumber(w) || !(w > 0))) {
              bad(`${path}.weight`, 'must be above 0');
            }
            const seed = scenario['level_seed'];
            if (
              seed !== undefined &&
              (!isFiniteNumber(seed) || !Number.isInteger(seed) || seed < 0 || seed > 0xffffffff)
            ) {
              bad(`${path}.level_seed`, 'must be a whole number from 0 to 4294967295');
            }
            const factors = scenario['amount_factors'];
            if (factors !== undefined) {
              if (!isObject(factors)) bad(`${path}.amount_factors`, 'must map item ids to factors');
              else {
                for (const [item, factor] of Object.entries(factors)) {
                  if (!itemSoils.has(item)) {
                    bad(`${path}.amount_factors.${item}`, 'is not an item of the load');
                  } else if (!isFiniteNumber(factor) || !(factor > 0)) {
                    bad(`${path}.amount_factors.${item}`, 'must be a factor above 0');
                  }
                }
              }
            }
            if (scenario['params'] !== undefined && !isObject(scenario['params'])) {
              bad(`${path}.params`, 'must map parameter keys to values');
            }
          });
        }
      }
    }
  }

  return issues.length > 0 ? err(issues) : ok(json as unknown as WashRecord);
}

/** As {@link validateWashRecord}, throwing {@link WashRecordError} with every problem. */
export function parseWashRecord(json: unknown): WashRecord {
  const result = validateWashRecord(json);
  if (!result.ok) throw new WashRecordError(result.error);
  return result.value;
}

/**
 * Standard deviations either side of the value that the `range` of a `visible_area`
 * observation is taken to span: the central 90 % of a normal error.
 */
// literal-ok-begin: named arithmetic control, documented where it is declared
export const RANGE_HALF_WIDTH_SDS = 1.645;
// literal-ok-end

/**
 * The uncertainty a stated range of a visible area stands for: the standard deviation of
 * ln(area + floor), with the range read as its central 90 %. `floorMm2` is the area below
 * which the reading does not tell a residue from none (`obs.areaFloorMm2`).
 */
export function rangeLogSd(range: readonly [number, number], floorMm2: number): number {
  return Math.log((range[1] + floorMm2) / (range[0] + floorMm2)) / (2 * RANGE_HALF_WIDTH_SDS);
}

/**
 * The standard uncertainty of an observation: its own, or, for a visible area that states a
 * range and no `sd`, the one its range stands for ({@link rangeLogSd} at the registered
 * default of `obs.areaFloorMm2`), or its method's; undefined if none.
 */
export function observationSd(
  record: WashRecord,
  observation: RecordObservation,
): number | undefined {
  if (observation.sd !== undefined) return observation.sd;
  if (observation.kind === 'visible_area' && observation.range !== undefined) {
    return rangeLogSd(observation.range, AREA_FLOOR_DEFAULT_MM2);
  }
  return record.provenance.methods[observation.method]?.sd;
}
