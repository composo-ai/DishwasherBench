/**
 * What the soil model knows about each catalogue soil by its id (docs/research/standards.md
 * sections 4.1, 4.3, 4.4, 10.3 and 13.3; docs/research/soils.md sections 5, 7.7 and 8.1;
 * docs/research/chemistry.md sections 4.2, 7 and 8.6).
 *
 * The catalogue gives a soil a mechanism class of eight; the first build mapped those to six
 * model classes and took everything else from the class: a milk film was judged by the
 * visibility of egg yolk, spinach by that of starch, every fat melted like butter, and a soil
 * whose catalogue entry has no solids fraction got that of its class (a tea film, stated dry,
 * was multiplied by 0.01). This table is the soil side's own record per soil id, until the
 * catalogue carries the same:
 *
 *   model class     the kinetic class, split by appearance and by melting where the dossiers
 *                   tell soils of one law apart (`SOIL_CLASS_PARENT`)
 *   appearance      the visibility class of standards 10.3; the model class of every soil has
 *                   a registered `visibleMass` inside the band of its appearance (tested)
 *   application     how the soil is laid on, which decides the scatter of its loading from
 *                   patch to patch (`soil.applicationCv`)
 *   solids          the mass fraction of the stated amount that is dry matter the wash has to
 *                   remove; 1 for a soil stated dry
 *   loading         the working loading of the covered area on the catalogue's basis, g/m2
 *   coverage        the share of the named region a record of the soil typically covers
 *   ageing          the heat history the soil usually has, and hours from soiling to the wash
 *   heat step       where the catalogue's name for a history overstates it, the heat step the
 *                   soil model reads instead (microwaved milk is "baked" in the catalogue,
 *                   160 C for an hour in the model, and is cooked dry at about 100 C)
 *
 * Units: g/m2, hours, mass fractions.
 */

