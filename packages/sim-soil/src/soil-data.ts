/** Soils whose usual heat history the catalogue names more harshly than the soil model reads it. */
const HEAT_AS: Readonly<Record<string, NonNullable<SoilDatum['heatAs']>>> = {
  // A microwave oven cooks 10 mL of milk dry at about 100 C in a quarter of an hour; the
  // catalogue's only history for it, `baked`, is an hour at 160 C in the soil model.
  iec_milk: { baked: 'cooked' },
  ikw_milk_microwaved: { baked: 'cooked' },
};

/** The soil data by catalogue soil id. */
export const SOIL_DATA: Readonly<Record<string, SoilDatum>> = Object.fromEntries(
  ROWS.map((row): [string, SoilDatum] => {
    const heatAs = HEAT_AS[row[0]];
    return [
      row[0],
      {
        id: row[0],
        modelClass: row[1],
        appearance: row[2],
        application: row[3],
        solidsFraction: row[4],
        solidsSource: row[5],
        basis: row[6],
        loading: row[7],
        loadingRange: [row[8], row[9]],
        coverage: row[10],
        heatHistory: row[11],
        ageH: row[12],
        ...(heatAs === undefined ? {} : { heatAs }),
        note: row[13],
      },
    ];
  }),
);

/** The soil data of a catalogue soil id, or undefined for an id this table does not know. */
export function soilData(soilTypeId: string): SoilDatum | undefined {
  return Object.prototype.hasOwnProperty.call(SOIL_DATA, soilTypeId)
    ? SOIL_DATA[soilTypeId]
    : undefined;
}

/**
 * The model class of a soil: that of its entry here, else the class the caller found for it
 * (the catalogue's mechanism class through {@link SOIL_CLASS_OF_MECHANISM}, or a model class
 * named directly).
 */
export function modelClassOf(soilTypeId: string, fallback: SoilModelClass): SoilModelClass {
  return soilData(soilTypeId)?.modelClass ?? fallback;
}

/** The model class the first build gave a mechanism class of the catalogue. */
export function modelClassOfMechanism(soilClass: SoilClassId): SoilModelClass {
  return SOIL_CLASS_OF_MECHANISM[soilClass];
}

/** The heat step the soil model reads for a heat history of a soil record. */
export function heatStepOf(soilTypeId: string, heatHistory: string): string {
  const as = soilData(soilTypeId)?.heatAs as Readonly<Record<string, string>> | undefined;
  return as?.[heatHistory] ?? heatHistory;
}

/**
 * The working amount (grams, on the soil's basis) and the dry mass (grams) of a soil on a
 * covered area (m2), from this table.
 */
export function workingAmount(
  soilTypeId: string,
  coveredAreaM2: number,
): { readonly amount_g: number; readonly dry_g: number } | undefined {
  const datum = soilData(soilTypeId);
  if (datum === undefined) return undefined;
  const amount = datum.loading * coveredAreaM2;
  return { amount_g: amount, dry_g: amount * datum.solidsFraction };
}
