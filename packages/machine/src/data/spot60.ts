/** One plate tine row of the lower rack: a front-back rail on a grid wire. */
function lowerRow(index: number, railX: number, front: boolean): TineRowDef {
  const rear = !front;
  return {
    id: `row_${index}`,
    label: `row ${index}`,
    runs: 'y',
    railAtMm: railX,
    // The rail is a wire of the upper grid layer (4.2 mm finished, top at z = 0).
    railZMm: -2.1,
    railSpanMm: front ? [-244.6, 0] : [0, 244.6],
    // CHOICE: nine tines at the stated 25 mm pitch in each half of the depth.
    tinePositionsMm: front ? arithmetic(-220, 25, 9) : arithmetic(20, 25, 9),
    // "8 deg toward the tub centre": front rows lean back, rear rows lean forward.
    leanToward: front ? '+y' : '-y',
    pitchMm: 25,
    // 62 mm (front) and 75 mm (rear) above the grid top.
    heightMm: (front ? 62 : 75) + 2.1,
    leanDeg: 8,
    wireDiameterMm: 4.2,
    tip: 'round',
    form: 'straight',
    hinge: rear
      ? {
          // CHOICE: a row on a front-back rail folds sideways; taken towards the centre line.
          foldsToward: railX < 0 ? '+x' : '-x',
          foldAngleDeg: 90,
          release: 'lever at the hinge rail',
        }
      : null,
    defaultState: 'up',
    provenance: prov(
      'generic',
      `${M} 2.4.2 (lower rack), 12.1 (racks.lower)`,
      RACK_PROVENANCE_NOTE,
      {
        railAt: 'estimated',
        tinePositions: 'estimated',
        railSpan: 'estimated',
        hinge: 'estimated',
      },
    ),
  };
}

